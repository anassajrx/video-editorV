"""Write the Kaggle kernel folder for one prep job, to be started with `kaggle kernels push -p <dir>`.

Usage: python3 platform/kaggle/make_kernel.py <out_dir> '<job json>'
Env:   KAGGLE_USERNAME (kernel owner), VE_REF (git ref the kernel downloads the code from, default: main)

The kernel code is a tiny bootstrap: JOB (no secrets) + download of the runner files from the public repo.
"""
import json
import os
import sys

REPO = "anassajrx/video-editorV"
FILES = ["platform/pylib/drive.py", "platform/pylib/status.py", "platform/kaggle/prep_runner.py",
         "local/colab/colab_prep.py", "local/colab/mic_sync.py"]

out, job = sys.argv[1], json.loads(sys.argv[2])
user = os.environ["KAGGLE_USERNAME"]
ref = os.environ.get("VE_REF", "main")
os.makedirs(out, exist_ok=True)
boot = f'''# Auto-generated by platform/kaggle/make_kernel.py: one prep job of the video platform.
import os, sys, urllib.request
JOB = {json.dumps(job, ensure_ascii=False)}
REF = {ref!r}
D = "/kaggle/working/ve-code"
os.makedirs(D, exist_ok=True)
for f in {FILES!r}:
    urllib.request.urlretrieve(f"https://raw.githubusercontent.com/{REPO}/{{REF}}/{{f}}", os.path.join(D, os.path.basename(f)))
sys.path.insert(0, D)
import prep_runner
prep_runner.main(JOB)
'''
open(os.path.join(out, "run.py"), "w").write(boot)
json.dump({
    "id": f"{user}/ve-prep",
    "title": "ve-prep",
    "code_file": "run.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": True,
    "enable_gpu": True,
    "enable_internet": True,
    "machine_shape": "NvidiaTeslaT4",
    "dataset_sources": [f"{user}/ve-secrets"],
    "competition_sources": [],
    "kernel_sources": [],
}, open(os.path.join(out, "kernel-metadata.json"), "w"), indent=1)
print(f"kernel folder ready: {out} ({user}/ve-prep, code from {REPO}@{ref})")
